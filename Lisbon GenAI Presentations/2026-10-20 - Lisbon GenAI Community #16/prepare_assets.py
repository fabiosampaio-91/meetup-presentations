def trim(im, pad=0):
    bbox = im.getchannel("A").getbbox() if im.mode == "RGBA" else im.getbbox()
    if not bbox:
        return im
    l, t, r, b = bbox
    return im.crop((max(0, l - pad), max(0, t - pad), min(im.width, r + pad), min(im.height, b + pad)))


def whiten_to_alpha(im, thresh=235):
    a = np.asarray(im.convert("RGBA")).copy()
    white = (a[..., :3] > thresh).all(axis=2)
    a[white, 3] = 0
    return Image.fromarray(a)


def flat_logo_upscale(im, inks, scale=8, blur=0.45):
    """Upscale a small flat-colour logo cropped from a raster (white background) into a crisp RGBA.

    Each pixel is modelled as white blended with one ink colour (alpha = ink coverage); the
    coverage map is upscaled, smoothed and re-thresholded, so edges come out clean instead of the
    soft blur a plain resize gives. `inks` is either a count (sampled from the crop's darkest
    pixels) or the logo's own ink colours, sampled from the poster beforehand.
    """
    rgb = np.asarray(im.convert("RGB")).astype(np.float32) / 255
    h, w, _ = rgb.shape
    if isinstance(inks, int):
        amt = 1 - rgb.min(axis=2)
        px = (rgb[amt > 0.55] * 255).astype(np.uint8)
        q = Image.fromarray(px.reshape(-1, 1, 3)).quantize(inks, method=Image.Quantize.MEDIANCUT)
        pal = np.array(q.getpalette()[: 3 * inks], dtype=np.float32).reshape(-1, 3) / 255
    else:
        pal = np.array([[int(c[i:i + 2], 16) for i in (1, 3, 5)] for c in inks], np.float32) / 255
    best = np.full((h, w), np.inf, np.float32)
    label = np.zeros((h, w), np.int32)
    alpha = np.zeros((h, w), np.float32)
    for i, ink in enumerate(pal):
        d = 1 - ink
        a = np.clip(((1 - rgb) @ d) / (d @ d + 1e-6), 0, 1)
        res = ((rgb - (1 - a[..., None] * d)) ** 2).sum(-1)
        upd = res < best
        best[upd], label[upd], alpha[upd] = res[upd], i, a[upd]
    size = (w * scale, h * scale)

    def up(arr):
        img = Image.fromarray((arr * 255).astype(np.uint8)).resize(size, Image.BICUBIC)
        return np.asarray(img.filter(ImageFilter.GaussianBlur(scale * blur))).astype(np.float32) / 255

    A_ = np.clip((up(alpha) - 0.32) / 0.36, 0, 1)
    A_ = A_ * A_ * (3 - 2 * A_)
    L = np.argmax(np.stack([up((label == i) * alpha) for i in range(len(pal))]), axis=0)
    out = np.dstack([(pal[L] * 255).astype(np.uint8), (A_ * 255).astype(np.uint8)])
    return trim(Image.fromarray(out, "RGBA"), pad=scale * 2)


def recolour_icon(im, accent=ACCENT):
    """xgeeks line-art icon -> GenAI palette: teal fills become the poster red-orange, navy lines black."""
    a = np.asarray(im.convert("RGBA")).astype(np.float32)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    teal = (g - r > 60) & (b - r > 30)                        # #00EBB6 and its anti-aliased edges
    k = np.clip((g - r) / 235.0, 0, 1)[..., None]             # how much teal is in the pixel
    base = a[..., :3] - k * np.array([0x00, 0xEB, 0xB6], np.float32)
    a[..., :3] = np.where(teal[..., None], np.clip(base + k * np.array(accent, np.float32), 0, 255), a[..., :3])
    navy = (r < 40) & (g < 70) & (b < 70) & ~teal              # #002E33 outlines -> black
    a[navy, :3] = 0
    return Image.fromarray(a.astype(np.uint8), "RGBA")


def svg_to_png(svg_bytes, width_px):
    """Render an SVG from the decks with headless Chrome on a transparent background."""
    import re
    s = svg_bytes.decode("utf-8", "ignore")
    vb = re.search(r'viewBox="([\d.\s-]+)"', s)
    if vb:
        _, _, vw, vh = map(float, vb.group(1).split())
    else:
        vw = float(re.search(r'width="([\d.]+)', s).group(1))
        vh = float(re.search(r'height="([\d.]+)', s).group(1))
    height_px = int(round(width_px * vh / vw))
    b64 = base64.b64encode(svg_bytes).decode()
    html = (f'<html><body style="margin:0;background:transparent">'
            f'<img src="data:image/svg+xml;base64,{b64}" style="display:block;width:{width_px}px;height:{height_px}px">'
            f'</body></html>')
    with tempfile.TemporaryDirectory() as td:
        hp, out = Path(td) / "s.html", Path(td) / "s.png"
        hp.write_text(html)
        subprocess.run([str(CHROME), "--headless=new", "--disable-gpu", "--hide-scrollbars",
                        "--default-background-color=00000000", f"--window-size={width_px},{height_px}",
                        f"--screenshot={out}", hp.as_uri()], check=True, capture_output=True, timeout=90)
        return trim(Image.open(out).convert("RGBA"), pad=4)


def save_rgb(im, path, quality=92, max_w=None):
    im = im.convert("RGB")
    if max_w and im.width > max_w:
        im = im.resize((max_w, round(im.height * max_w / im.width)), Image.LANCZOS)
    im.save(path, quality=quality)


