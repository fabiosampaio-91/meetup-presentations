def media(zf, name):
    return Image.open(io.BytesIO(zf.read(f"ppt/media/{name}")))


def trim(im, pad=0):
    bbox = im.getchannel("A").getbbox() if im.mode == "RGBA" else im.getbbox()
    if not bbox:
        return im
    l, t, r, b = bbox
    return im.crop((max(0, l - pad), max(0, t - pad), min(im.width, r + pad), min(im.height, b + pad)))


def flat_logo_upscale(im, inks, scale=8, blur=0.45):
    """Upscale a small flat-colour logo cropped from a raster (white background) into a crisp RGBA.

    Same technique as the Lisbon GenAI #16 deck: each pixel is white blended with one ink colour
    (alpha = ink coverage); the coverage map is upscaled, smoothed and re-thresholded.
    `inks` are the logo's own colours, sampled from the banner beforehand.
    """
    rgb = np.asarray(im.convert("RGB")).astype(np.float32) / 255
    h, w, _ = rgb.shape
    pal = np.array([[int(c[i:i + 2], 16) for i in (1, 3, 5)] for c in inks], np.float32) / 255
    best = np.full((h, w), np.inf, np.float32)
    label = np.zeros((h, w), np.int32)
    alpha = np.zeros((h, w), np.float32)
    for i, ink in enumerate(pal):
        d = 1 - ink
        a = np.clip(((1 - rgb) @ d) / (d @ d + 1e-6), 0, 1)
        res = ((rgb - (1 - a[..., None] * d)) ** 2).sum(-1)
        upd = res < best
        best[upd], label[upd], alpha[upd] = res[upd], i, a[upd]
    size = (w * scale, h * scale)

    def up(arr):
        img = Image.fromarray((arr * 255).astype(np.uint8)).resize(size, Image.BICUBIC)
        return np.asarray(img.filter(ImageFilter.GaussianBlur(scale * blur))).astype(np.float32) / 255

    A_ = np.clip((up(alpha) - 0.32) / 0.36, 0, 1)
    A_ = A_ * A_ * (3 - 2 * A_)
    L = np.argmax(np.stack([up((label == i) * alpha) for i in range(len(pal))]), axis=0)
    out = np.dstack([(pal[L] * 255).astype(np.uint8), (A_ * 255).astype(np.uint8)])
    return trim(Image.fromarray(out, "RGBA"), pad=scale * 2)


def circle_src(im, box=None, size=480):
    """Square crop (centre or `box`) for the round organizer / speaker avatars."""
    im = im.convert("RGB")
    if box:
        im = im.crop(box)
    s = min(im.size)
    l, t = (im.width - s) // 2, (im.height - s) // 2
    return im.crop((l, t, l + s, t + s)).resize((size, size), Image.LANCZOS)


# --- 1. Banner (cover) ----------------------------------------------------------------------
# 3130x1643 (no black frame on this export): pad to 16:9 with its own top/bottom rows (flat navy at
# the top, the maroon end of the gradient at the bottom) so the cards are not cropped.
banner = Image.open(BANNER).convert("RGB")
W, H = banner.size
pad = round(W * 9 / 16) - H
arr = np.pad(np.asarray(banner), ((pad // 2, pad - pad // 2), (0, 0), (0, 0)), mode="edge")
Image.fromarray(arr).save(A / "banner" / "devops-braga-34-banner.png")

# --- 2. Logos ------------------------------------------------------------------------------
media(VTT, "image1.png").save(A / "logos" / "synvert-xgeeks-navy.png")
# DevOps Braga: the group's own key photo on Meetup (the logo over its keyboard photo, 1920x1080)
dvb = Image.open(SRC / "logos" / "devops-braga (meetup group photo 470286596).jpeg").convert("RGB")
dvb.thumbnail((1600, 1600), Image.LANCZOS)
dvb.save(A / "logos" / "devops-braga.jpg", quality=92)
# KCD Porto x DevOpsDays Portugal lockup, cut from an official keynote card
keys = sorted((AWS / "kcd-keynotes").glob("*.jpeg"))
Image.open(keys[0]).convert("RGB").crop((60, 52, 366, 210)).save(A / "logos" / "kcd-porto-devopsdays.jpg", quality=95)
# Sponsor / partner logos that only exist in the banner's logo strip: rebuilt crisp from their own inks.
BANNER_LOGOS = {                       # box in banner px, ink colours sampled from the banner
    "gdg.png": ((565, 180, 710, 265), ["#109D58", "#4385F3", "#FABE0D", "#E94638"]),
    "outsystems-user-groups.png": ((770, 180, 1070, 265), ["#010101"]),
    "outsystems.png": ((1115, 190, 1470, 265), ["#FF2400", "#333333"]),
}
for out_name, (box, inks) in BANNER_LOGOS.items():
    flat_logo_upscale(banner.crop(box), inks, scale=6).save(A / "logos" / out_name)

# --- 3. Speakers (agenda), cropped from the banner's speaker cards --------------------------
for slug, top in (("antonio-ojea", 175), ("nuno-mendes", 628), ("murilo-rosendo", 1081)):
    circle_src(banner, (1660, top, 2030, top + 350)).save(A / "photos" / f"{slug}.jpg", quality=92)

# --- 4. Organizers: Meetup profile photos (ids from the group page JSON) ---------------------
for p in sorted((SRC / "organizers").glob("* (meetup member photo *).webp")):
    circle_src(Image.open(p), size=320).save(A / "photos" / f"org-{p.name.split(' (')[0]}.png")

# --- 5. KCD Porto keynote cards (official) ---------------------------------------------------
for i, p in enumerate(keys, 1):
    im = Image.open(p).convert("RGB")
    im.thumbnail((720, 720), Image.LANCZOS)
    im.save(A / "photos" / f"kcd-keynote-{i}.jpg", quality=92)

for p in (A / "logos").glob("*.png"):
    im = Image.open(p)
    if max(im.size) > 1400:
        im.thumbnail((1400, 1400), Image.LANCZOS)
        im.save(p)

print("assets prepared ->", A)
